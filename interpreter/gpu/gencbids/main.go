// gencbids generates cbid_names.go, the CUDA API function names for CUPTI
// callback IDs, from CUPTI's cupti_runtime_cbid.h and cupti_driver_cbid.h.
//
//	make cbid-names CUDA_INCLUDE=/usr/local/cuda/include
//
// CUPTI only appends to these enums, so the newest headers cover every
// earlier CUDA release.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
)

var (
	entry = regexp.MustCompile(`^\s*CUPTI_(RUNTIME|DRIVER)_TRACE_CBID_(\w+)\s*=\s*(\d+),`)
	// Runtime cbid names carry the CUDA version that introduced the entry
	// point (cudaMalloc_v3020); the exported function has no such suffix.
	runtimeVersion = regexp.MustCompile(`_v\d+$`)
)

func parse(path string) (map[int]string, int) {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	names := make(map[int]string)
	maxID := 0
	s := bufio.NewScanner(f)
	for s.Scan() {
		m := entry.FindStringSubmatch(s.Text())
		if m == nil || m[2] == "INVALID" || m[2] == "SIZE" {
			continue
		}
		id, err := strconv.Atoi(m[3])
		if err != nil {
			log.Fatal(err)
		}
		name := m[2]
		if m[1] == "RUNTIME" {
			name = runtimeVersion.ReplaceAllString(name, "")
		}
		names[id] = name
		maxID = max(maxID, id)
	}
	if err := s.Err(); err != nil {
		log.Fatal(err)
	}
	return names, maxID
}

func emit(b *bytes.Buffer, varName, doc string, names map[int]string, maxID int) {
	fmt.Fprintf(b, "// %s\n", doc)
	fmt.Fprintf(b, "var %s = [...]string{\n", varName)
	for id := 1; id <= maxID; id++ {
		if name, ok := names[id]; ok {
			fmt.Fprintf(b, "\t%d: %q,\n", id, name)
		}
	}
	b.WriteString("}\n\n")
}

func main() {
	if len(os.Args) != 3 {
		log.Fatalf("usage: %s <cupti include dir> <output.go>", os.Args[0])
	}
	runtime, maxRuntime := parse(filepath.Join(os.Args[1], "cupti_runtime_cbid.h"))
	driver, maxDriver := parse(filepath.Join(os.Args[1], "cupti_driver_cbid.h"))

	var b bytes.Buffer
	b.WriteString("// Code generated by gencbids from CUPTI's cupti_runtime_cbid.h and\n")
	b.WriteString("// cupti_driver_cbid.h; DO NOT EDIT.\n\n")
	b.WriteString("package gpu\n\n")
	emit(&b, "runtimeCbidNames", "runtimeCbidNames maps CUPTI runtime API cbids to function names.",
		runtime, maxRuntime)
	emit(&b, "driverCbidNames", "driverCbidNames maps CUPTI driver API cbids to function names.",
		driver, maxDriver)

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		log.Fatal(err)
	}
}
