//! Translates Go symbols into symbfile ranges.
//!
//! This is currently still very basic and doesn't support inline functions
//! or constructing line tables.

use crate::{debug, gosym, objfile, symbfile, AnyError};
use fallible_iterator::FallibleIterator as _;
use std::collections::HashMap;

/// Result type shorthand.
pub type Result<T = (), E = Error> = std::result::Result<T, E>;

/// Errors that can occur during Go symbol extraction.
#[non_exhaustive]
#[allow(missing_docs)]
#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("go metadata parsing error: {0}")]
    Gosym(#[from] gosym::Error),

    #[error("visitor returned an error: {0}")]
    Visitor(#[source] AnyError),

    #[error("line mapping failed with error: {0}")]
    GoSymbolBadLineMapping(#[source] AnyError),
}

/// Go symbol extraction statistics.
#[derive(Debug, Default)]
pub struct Stats {
    /// Functions that we succeeded extracting symbols from.
    pub funcs_ok: u64,

    /// Functions that we had to skip due to parsing errors.
    pub funcs_skipped: u64,

    /// Whether the executable was detected to be a Go executable.
    pub is_go_binary: bool,
}

/// `.gopclntab` symbol extractor.
pub struct Extractor<'obj>(&'obj objfile::Reader<'obj>);

impl<'obj> Extractor<'obj> {
    /// Create a new extractor.
    pub fn new(obj: &'obj objfile::Reader<'obj>) -> Self {
        Extractor(obj)
    }
}

impl<'obj> super::RangeExtractor for Extractor<'obj> {
    fn extract(&self, visitor: super::RangeVisitor<'_>) -> super::Result<Option<super::Stats>> {
        extract_ranges(self.0, visitor)
            .map(|x| Some(super::Stats::Go(x)))
            .map_err(super::Error::Go)
    }
}

/// Wraps another range extractor, filling in missing
/// [`symbfile::Range::start_line`] values from `.gopclntab`.
///
/// Go only emits `DW_AT_decl_line` since Go 1.22, while `.gopclntab` carries
/// the start line of every function (including inlined ones) since Go 1.20.
/// When DWARF takes precedence over `.gopclntab`, as it does in the default
/// extractor order, Go 1.20 and 1.21 binaries would otherwise end up without
/// any start lines. Functions without DWARF info (e.g. assembly) benefit too.
///
/// Ranges that already have a start line are passed through as-is, and non-Go
/// executables are passed through entirely unchanged.
pub struct StartLineBackfill<'obj, E> {
    obj: &'obj objfile::Reader<'obj>,
    inner: E,
}

impl<'obj, E> StartLineBackfill<'obj, E> {
    /// Wrap `inner`, backfilling start lines from the Go runtime info in `obj`.
    pub fn new(obj: &'obj objfile::Reader<'obj>, inner: E) -> Self {
        Self { obj, inner }
    }
}

impl<E: super::RangeExtractor> super::RangeExtractor for StartLineBackfill<'_, E> {
    fn extract(&self, visitor: super::RangeVisitor<'_>) -> super::Result<Option<super::Stats>> {
        let go = match gosym::GoRuntimeInfo::open(self.obj) {
            Ok(x) => x,
            Err(gosym::Error::GopclntabNotFound) => return self.inner.extract(visitor),
            Err(e) => {
                debug!("Unable to read Go runtime info, not backfilling start lines: {e:?}");
                return self.inner.extract(visitor);
            }
        };

        // Only needed for inline functions lacking DWARF start lines, which
        // are rare outside of Go < 1.22: build lazily.
        let mut inline_start_lines = None;

        self.inner.extract(&mut |mut range| {
            if range.start_line.is_none() {
                range.start_line = if range.depth == 0 {
                    func_start_line(&go, &range)
                } else {
                    let start_lines = inline_start_lines.get_or_insert_with(|| {
                        collect_inline_start_lines(&go).unwrap_or_else(|e| {
                            debug!("Unable to read Go inline trees: {e:?}");
                            HashMap::new()
                        })
                    });
                    lookup_start_line(start_lines, &range.func)
                };
            }
            visitor(range)
        })
    }
}

/// Looks up the start line of the top-level function containing `range`.
///
/// This goes by address rather than by name: the ABI wrappers generated by
/// the Go compiler share their name with the function they wrap, but have a
/// start line of 1 (in `<autogenerated>`).
fn func_start_line(go: &gosym::GoRuntimeInfo<'_>, range: &symbfile::Range) -> Option<u32> {
    let func = go.find_func(range.elf_va).ok()??;
    let name = func.name().ok()?;
    if name != range.func && abbreviate_generic(&range.func).as_deref() != Some(name) {
        return None;
    }
    func.start_line().filter(|&x| x != 0)
}

/// Looks up the start line of an inlined function by its (DWARF) name.
fn lookup_start_line(start_lines: &HashMap<&str, u32>, func: &str) -> Option<u32> {
    if let Some(&line) = start_lines.get(func) {
        return Some(line);
    }
    start_lines.get(abbreviate_generic(func)?.as_str()).copied()
}

/// Abbreviates a generic function name the way that the Go 1.20 and 1.21
/// linkers do in `.gopclntab`: everything between the first `[` and the last
/// `]` is replaced by `[...]`. DWARF always has the full name.
fn abbreviate_generic(func: &str) -> Option<String> {
    let (open, close) = (func.find('[')?, func.rfind(']')?);
    if close < open {
        return None;
    }
    Some(format!("{}[...]{}", &func[..open], &func[close + 1..]))
}

/// Collects the start lines of all inlined functions in `.gopclntab` by name.
///
/// Unlike top-level functions, inlined functions are never ABI wrappers, so
/// their names unambiguously identify them.
fn collect_inline_start_lines<'obj>(
    go: &gosym::GoRuntimeInfo<'obj>,
) -> Result<HashMap<&'obj str, u32>> {
    let mut start_lines = HashMap::new();
    let mut func_iter = go.funcs()?;
    while let Some(func) = func_iter.next()? {
        // Every inlined function is the innermost frame for at least one PC:
        // its own instructions, or the inline mark at its child's `parent_pc`
        // that the Go runtime itself resolves parents with. Visiting the
        // innermost call for each PC thus covers the whole inline tree.
        let Some(mut inline_iter) = func.inline_mapping()? else {
            continue;
        };
        while let Some((_, call)) = inline_iter.next()? {
            let Some(call) = call else {
                continue;
            };
            if let Some(line) = call.start_line().filter(|&x| x != 0) {
                start_lines.entry(call.name()?).or_insert(line);
            }
        }
    }

    Ok(start_lines)
}

fn find_func_end(func: &gosym::Func<'_, '_>) -> Result<Option<u64>> {
    let mut end: Option<u64> = None;
    let mut iter = func.line_mapping()?;
    loop {
        match iter.next()? {
            Some((rng, _)) => {
                if let Some(e) = end {
                    if rng.end < e {
                        continue;
                    }
                }
                end = Some(rng.end)
            }
            None => break,
        }
    }
    Ok(end)
}

fn extract_ranges(obj: &objfile::Reader<'_>, visitor: super::RangeVisitor<'_>) -> Result<Stats> {
    let mut stats = Stats::default();

    let go = match gosym::GoRuntimeInfo::open(obj) {
        Ok(x) => x,
        Err(gosym::Error::GopclntabNotFound) => return Ok(stats),
        Err(other) => return Err(other.into()),
    };

    stats.is_go_binary = true;

    let mut func_iter = go.funcs()?;
    while let Some(func) = func_iter.next()? {
        let end = match find_func_end(&func) {
            Ok(Some(e)) => e,
            Ok(None) => {
                debug!(
                    "WARN: unable to determine end of function ({})",
                    func.name()?
                );
                stats.funcs_skipped += 1;
                continue;
            }
            Err(Error::Gosym(gosym::Error::BadLineNumber)) => {
                // skip function once we hit a BadLineNumber error
                debug!("WARN: bad line number of function ({})", func.name()?);
                stats.funcs_skipped += 1;
                continue;
            }
            Err(e) => {
                return Err(Error::GoSymbolBadLineMapping(e.into()));
            }
        };

        let length = end.saturating_sub(func.start_addr());

        if length == 0 {
            debug!("WARN: zero function length ({})", func.name()?);
            stats.funcs_skipped += 1;
            continue;
        }

        // Pick first file and hope for the best. So far this has worked for
        // all samples that I've looked at. Even in the presence of inline
        // functions there will always be a prologue that has the file of the
        // outer function assigned to it.
        let file = func
            .file_mapping()?
            .find_map(|(_, name)| Ok(name.map(|x| x.to_owned())))?;

        let range = symbfile::Range {
            elf_va: func.start_addr(),
            length: length as _,
            func: func.name()?.to_owned(),
            file,
            call_file: None,
            call_line: None,
            call_discriminator: 0,
            depth: 0,
            line_table: Default::default(),
            // Available for Go >= 1.20; `None` otherwise.
            start_line: func.start_line().filter(|&x| x != 0),
        };

        visitor(range).map_err(Error::Visitor)?;

        stats.funcs_ok += 1;
    }

    Ok(stats)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tests::go_testdata;

    #[test]
    fn test_extract_ranges() -> Result<(), AnyError> {
        for test_file in go_testdata() {
            let obj = objfile::File::load(&test_file)?;
            let obj = obj.parse()?;

            let mut ranges = Vec::new();
            let mut visitor = |range: symbfile::Range| -> Result<(), AnyError> {
                ranges.push(range);
                Ok(())
            };
            extract_ranges(&obj, &mut visitor)?;

            // Verify we got some ranges
            assert!(!ranges.is_empty());

            // Verify ranges contains the main function
            let main_main = ranges
                .iter()
                .find(|range| {
                    range.func == "main.main"
                        && range.file.is_some()
                        && range.file.as_ref().unwrap().ends_with("main.go")
                })
                .unwrap_or_else(|| panic!("main.main not found in {:?}", test_file));

            // All test binaries are built with Go >= 1.20, so the per-function
            // start line is available and must point at the `func main()` line
            // (line 5 of testdata/main.go).
            assert_eq!(
                main_main.start_line,
                Some(5),
                "unexpected start_line for main.main in {:?}",
                test_file
            );

            // Verify ranges are valid
            for range in ranges {
                // Basic validity checks
                assert!(range.elf_va > 0);
                assert!(range.length > 0);
                assert!(!range.func.is_empty());
                assert!(range.file.is_some());
            }
        }
        Ok(())
    }

    #[test]
    fn start_line_backfill() -> Result<(), AnyError> {
        use crate::dwarf;
        use crate::symbconv::dwarf::Extractor as DwarfExtractor;
        use crate::symbconv::RangeExtractor;

        fn extract(extr: &dyn RangeExtractor) -> Vec<symbfile::Range> {
            let mut ranges = Vec::new();
            extr.extract(&mut |range| {
                ranges.push(range);
                Ok(())
            })
            .unwrap();
            ranges
        }

        for test_file in go_testdata() {
            let obj = objfile::File::load(&test_file)?;
            let obj = obj.parse()?;
            let dw = dwarf::Sections::load(&obj)?;
            let go = gosym::GoRuntimeInfo::open(&obj)?;

            let plain = extract(&DwarfExtractor::new(&dw));
            let backfilled = extract(&StartLineBackfill::new(&obj, DwarfExtractor::new(&dw)));
            assert_eq!(plain.len(), backfilled.len());

            // Go only emits `DW_AT_decl_line` since 1.22, but `.gopclntab`
            // has start lines for every single function in our test binaries.
            if test_file.ends_with("go-1.20.14") {
                assert!(plain.iter().all(|x| x.start_line.is_none()));
            }

            // Where DWARF has start lines, they agree with `.gopclntab`. This
            // includes the ABI wrappers that share their name with the function
            // they wrap, which is why top-level functions go by address.
            let inline_start_lines = collect_inline_start_lines(&go)?;
            for (plain, backfilled) in plain.iter().zip(&backfilled) {
                let from_gopclntab = if backfilled.depth == 0 {
                    go.find_func(backfilled.elf_va)?.unwrap().start_line()
                } else {
                    lookup_start_line(&inline_start_lines, &backfilled.func)
                };
                assert!(from_gopclntab.is_some(), "{test_file:?}: {backfilled:?}");
                assert_eq!(backfilled.start_line, from_gopclntab, "{test_file:?}");
                if plain.start_line.is_some() {
                    assert_eq!(plain.start_line, from_gopclntab, "{test_file:?}");
                }
            }

            // `func main()` is at line 5 of testdata/main.go.
            let main_main = backfilled
                .iter()
                .find(|x| x.func == "main.main" && x.depth == 0)
                .unwrap();
            assert_eq!(main_main.start_line, Some(5), "{test_file:?}");
        }

        Ok(())
    }
}
